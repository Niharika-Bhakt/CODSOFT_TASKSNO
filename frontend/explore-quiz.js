let selectedCategory =
    localStorage.getItem("exploreQuiz") || "";

let currentQuestions = [];
let currentQuestion = 0;
let score = 0;
let selectedAnswer = null;

const quizCategory =
    document.getElementById("quizCategory");

const quizTitle =
    document.getElementById("quizTitle");

const currentQuestionElement =
    document.getElementById("currentQuestion");

const totalQuestions =
    document.getElementById("totalQuestions");

const scoreElement =
    document.getElementById("score");

const questionNumber =
    document.getElementById("questionNumber");

const questionText =
    document.getElementById("questionText");

const optionButtons =
    document.querySelectorAll(".option");

const optionA =
    document.getElementById("optionA");

const optionB =
    document.getElementById("optionB");

const optionC =
    document.getElementById("optionC");

const optionD =
    document.getElementById("optionD");

const nextButton =
    document.getElementById("nextButton");

const progressBar =
    document.getElementById("progressBar");

const feedback =
    document.getElementById("feedback");

const questionCard =
    document.getElementById("questionCard");

const resultCard =
    document.getElementById("resultCard");

const finalScore =
    document.getElementById("finalScore");

const percentage =
    document.getElementById("percentage");

const resultTitle =
    document.getElementById("resultTitle");

const resultMessage =
    document.getElementById("resultMessage");

const retryButton =
    document.getElementById("retryButton");


function loadQuiz() {

    if (!selectedCategory ||
        !quizData[selectedCategory]) {

        alert("Explore quiz not found.");

        window.location.href =
            "explore.html";

        return;
    }

    currentQuestions =
        quizData[selectedCategory];

    currentQuestion = 0;
    score = 0;
    selectedAnswer = null;

    quizCategory.textContent =
        selectedCategory;

    quizTitle.textContent =
        selectedCategory + " Quiz";

    totalQuestions.textContent =
        currentQuestions.length;

    scoreElement.textContent =
        "0";

    questionCard.style.display =
        "block";

    resultCard.style.display =
        "none";

    showQuestion();
}


function showQuestion() {

    const item =
        currentQuestions[currentQuestion];

    if (!item) {
        showResult();
        return;
    }

    selectedAnswer = null;

    const number =
        currentQuestion + 1;

    currentQuestionElement.textContent =
        number;

    questionNumber.textContent =
        String(number).padStart(2, "0");

    questionText.textContent =
        item.q;

    optionA.textContent =
        item.a[0];

    optionB.textContent =
        item.a[1];

    optionC.textContent =
        item.a[2];

    optionD.textContent =
        item.a[3];

    optionButtons.forEach(button => {

        button.classList.remove(
            "selected",
            "correct",
            "wrong"
        );

        button.disabled = false;

    });

    feedback.textContent = "";

    feedback.className =
        "feedback";

    nextButton.disabled =
        true;

    nextButton.textContent =
        currentQuestion ===
        currentQuestions.length - 1
            ? "Finish Quiz"
            : "Next Question →";

    const percent =
        Math.round(
            (number /
                currentQuestions.length) *
            100
        );

    progressBar.style.width =
        percent + "%";
}


optionButtons.forEach(button => {

    button.addEventListener(
        "click",
        function () {

            selectedAnswer =
                this.dataset.option;

            optionButtons.forEach(btn => {

                btn.classList.remove(
                    "selected"
                );

            });

            this.classList.add(
                "selected"
            );

            nextButton.disabled =
                false;
        }
    );

});


nextButton.addEventListener(
    "click",
    function () {

        if (!selectedAnswer) {
            return;
        }

        const item =
            currentQuestions[currentQuestion];

        optionButtons.forEach(button => {
            button.disabled = true;
        });

        if (selectedAnswer === item.answer) {

            score++;

            scoreElement.textContent =
                score;

            const selectedButton =
                document.querySelector(
                    `.option[data-option="${selectedAnswer}"]`
                );

            if (selectedButton) {

                selectedButton.classList.add(
                    "correct"
                );
            }

        } else {

            const selectedButton =
                document.querySelector(
                    `.option[data-option="${selectedAnswer}"]`
                );

            if (selectedButton) {

                selectedButton.classList.add(
                    "wrong"
                );
            }

            const correctButton =
                document.querySelector(
                    `.option[data-option="${item.answer}"]`
                );

            if (correctButton) {

                correctButton.classList.add(
                    "correct"
                );
            }
        }

        setTimeout(() => {

            if (
                currentQuestion ===
                currentQuestions.length - 1
            ) {

                showResult();

            } else {

                currentQuestion++;

                showQuestion();

            }

        }, 500);

    }
);


function showResult() {

    questionCard.style.display =
        "none";

    resultCard.style.display =
        "block";

    const total =
        currentQuestions.length;

    const percent =
        Math.round(
            (score / total) * 100
        );

    finalScore.textContent =
        score + " / " + total;

    percentage.textContent =
        percent + "%";

    if (percent === 100) {

        resultTitle.textContent =
            "Perfect Score! 🏆";

        resultMessage.textContent =
            "Amazing! You answered every question correctly.";

    } else if (percent >= 80) {

        resultTitle.textContent =
            "Excellent! 🔥";

        resultMessage.textContent =
            "Fantastic performance!";

    } else if (percent >= 60) {

        resultTitle.textContent =
            "Great Job! 👏";

        resultMessage.textContent =
            "Great attempt! Keep learning.";

    } else if (percent >= 40) {

        resultTitle.textContent =
            "Good Attempt! 💜";

        resultMessage.textContent =
            "Keep practicing and try again.";

    } else {

        resultTitle.textContent =
            "Keep Learning! 🌱";

        resultMessage.textContent =
            "Don't give up. Try again!";

    }

    progressBar.style.width =
        "100%";
}


retryButton.addEventListener(
    "click",
    function () {

        currentQuestion = 0;
        score = 0;
        selectedAnswer = null;

        scoreElement.textContent =
            "0";

        resultCard.style.display =
            "none";

        questionCard.style.display =
            "block";

        showQuestion();

    }
);
async function connectBackend() {

    try {

        const response =
            await fetch(
                "http://localhost:5000/api/quizzes"
            );

        if (!response.ok) {
            throw new Error("Failed to fetch quizzes");
        }

        const quizzes =
            await response.json();

        const backendQuiz =
            quizzes.find(
                quiz =>
                    quiz.title ===
                    selectedCategory
            );

        if (backendQuiz &&
            backendQuiz.questions &&
            backendQuiz.questions.length > 0) {

            currentQuestions =
                backendQuiz.questions.map(
                    question => {

                        return {
                            q: question.questionText,
                            a: question.options,
                            answer: question.correctAnswer
                        };

                    }
                );

            quizCategory.textContent =
                selectedCategory;

            quizTitle.textContent =
                selectedCategory + " Quiz";

            totalQuestions.textContent =
                currentQuestions.length;

            currentQuestion = 0;
            score = 0;
            selectedAnswer = null;

            scoreElement.textContent =
                "0";

            questionCard.style.display =
                "block";

            resultCard.style.display =
                "none";

            showQuestion();

        } else {

            loadQuiz();

        }

    } catch (error) {

        console.error(
            "Backend connection failed:",
            error
        );

        loadQuiz();

    }

}


connectBackend();